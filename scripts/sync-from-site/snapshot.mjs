// Snapshot itspatmorgan.com's content into the itspatmorgan.com prototype as typed modules with static image imports.
// usage: node scripts/sync-from-site/snapshot.mjs   (SITE=<path> to point at another checkout)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SITE = path.resolve(process.env.SITE ?? path.join(ROOT, '../itspatmorgan.com'));
const PROTO = path.join(ROOT, 'src/prototypes/patrick/itspatmorgan-com');
const DATA = path.join(PROTO, '_data');
const ASSETS = path.join(PROTO, 'assets/site');
const pnpm = name => {
  const dir = fs.readdirSync(path.join(SITE, 'node_modules/.pnpm')).filter(d => d.startsWith(name.replace('/', '+') + '@')).sort().at(-1);
  return path.join(SITE, 'node_modules/.pnpm', dir, 'node_modules', name);
};
const load = async name => import(path.join(pnpm(name), JSON.parse(fs.readFileSync(path.join(pnpm(name), 'package.json'))).exports?.['.']?.default ?? JSON.parse(fs.readFileSync(path.join(pnpm(name), 'package.json'))).main ?? 'index.js'));
const YAML = await import(path.join(SITE, 'node_modules/yaml/dist/index.js'));
const { unified } = await load('unified');
const remarkParse = (await load('remark-parse')).default;
const remarkGfm = (await load('remark-gfm')).default;
const remarkRehype = (await load('remark-rehype')).default;
const rehypeStringify = (await load('rehype-stringify')).default;

fs.mkdirSync(DATA, { recursive: true });

function frontmatter(file) {
  const text = fs.readFileSync(file, 'utf8');
  const m = text.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  return { data: YAML.parse(m[1]), body: m[2] };
}

// Images become static imports; values that are image URLs are replaced by the import's name.
class Images {
  constructor(from) { this.from = from; this.map = new Map(); }
  ref(url) {
    if (!url?.startsWith('/images/')) return url;
    if (!this.map.has(url)) {
      const src = path.join(SITE, 'public', url);
      const dst = path.join(ASSETS, url.replace(/^\/images\//, ''));
      fs.mkdirSync(path.dirname(dst), { recursive: true });
      fs.copyFileSync(src, dst);
      this.map.set(url, { name: `img${this.map.size}`, dst });
    }
    return { __image: this.map.get(url).name };
  }
  imports() {
    return [...this.map.values()].map(({ name, dst }) => `import ${name} from '${path.relative(path.dirname(this.from), dst).replace(/^(?!\.)/, './')}';`).join('\n');
  }
}
const literal = value => JSON.stringify(value, null, 2).replace(/\{\s*"__image": "(img\d+)"\s*\}/g, '$1');
const write = (file, header, images, body) =>
  fs.writeFileSync(path.join(DATA, file), `${header}\n${images.imports()}\n\n${body}`);
const tsData = async file => import(path.join(SITE, 'src/data', file));

// Projects: the case study cards and pages.
{
  const images = new Images(path.join(DATA, 'projects.ts'));
  const projects = fs.readdirSync(path.join(SITE, 'src/content/projects'))
    .filter(f => /\.mdx?$/.test(f))
    .map(f => ({ id: f.replace(/\.mdx?$/, ''), ...frontmatter(path.join(SITE, 'src/content/projects', f)).data }))
    .filter(p => !p.draft)
    .sort((a, b) => a.sortOrder - b.sortOrder)
    .map(({ thumbnail, thumbnailDark, thumbnailWide, thumbnailWideDark, heroImage, caseStudy, draft, ...p }) => ({
      ...p,
      ...(thumbnailWide ?? thumbnail ? { image: images.ref(thumbnailWide ?? thumbnail) } : {}),
      ...(caseStudy ? { caseStudy: { ...caseStudy, company: { ...caseStudy.company, logo: images.ref(caseStudy.company.logo) }, shareImage: undefined } } : {}),
    }));
  write('projects.ts', `// Case studies, from itspatmorgan.com's src/content/projects/ frontmatter (drafts left out). Generated by a snapshot script; edit freely.`, images,
    `export type CaseStudy = { company: { name: string; logo: string }; subline: string; shareDescription?: string; brief: { when: string; role: string; team: string; outcome: string }; slides: Record<string, { title: string; line?: string }> };
export type Project = { id: string; title: string; type: 'professional' | 'experiment'; description: string; summary?: string; skills: string[]; sortOrder: number; image?: string; caseStudy?: CaseStudy };

export const projects: Project[] = ${literal(projects)};

export const project = (id: string) => {
  const found = projects.find(p => p.id === id);
  if (!found) throw new Error(\`Missing project \${id}\`);
  return found;
};
`);
}

// Writing: every article's listing, and bodies for a representative sample only. Together the sample covers all five
// hero generators, all five themes, inline images, and blockquote-, list- and heading-heavy prose.
const ARTICLE_SAMPLE = [
  'how-i-rebuilt-my-portfolio-with-claude-code',
  '8-design-breakthroughs-defining-ais-future',
  '50-principles-of-unknown-arts',
  '3-models-for-framing-software-complexity',
  'surviving-the-taste-gap',
];
{
  const images = new Images(path.join(DATA, 'writing.ts'));
  const render = unified().use(remarkParse).use(remarkGfm).use(remarkRehype, { allowDangerousHtml: true }).use(rehypeStringify, { allowDangerousHtml: true });
  const posts = [];
  for (const f of fs.readdirSync(path.join(SITE, 'src/content/writing')).filter(f => /\.mdx?$/.test(f))) {
    const { data, body } = frontmatter(path.join(SITE, 'src/content/writing', f));
    if (data.draft) continue;
    const id = f.replace(/\.mdx?$/, '');
    let html;
    if (ARTICLE_SAMPLE.includes(id)) {
      html = String(await render.process(body));
      html = html.replace(/(src=")(\/images\/[^"]+)(")/g, (_, a, url, b) => `${a}{{${images.ref(url).__image}}}${b}`);
    }
    posts.push({
      id,
      title: data.title,
      description: data.description,
      publishedDate: new Date(data.publishedDate).toISOString().slice(0, 10),
      theme: data.theme,
      visual: data.visual && (({ version, theme, ...visual }) => visual)(data.visual),
      canonicalUrl: data.canonicalUrl,
      ...(html ? { html } : {}),
    });
  }
  posts.sort((a, b) => b.publishedDate.localeCompare(a.publishedDate));
  const imageTable = [...images.map.values()].map(({ name }) => name);
  write('writing.ts', `// Articles, from itspatmorgan.com's src/content/writing/ (drafts left out). Bodies, rendered with remark-gfm, only for the sample. Generated by a snapshot script.`, images,
    `import type { GeneratorConfig, LayerColor } from '@/systems/website/components/generative-art';

/** \`html\` is present only for the sampled articles; the rest link to the live site. */
export type Post = { id: string; title: string; description: string; publishedDate: string; theme?: string; canonicalUrl?: string; visual?: { background?: string; generator: GeneratorConfig; lightMode?: { color: LayerColor; opacity: number; strokeWidth?: number }; texture?: number; grain?: number }; html?: string };

const images: Record<string, string> = { ${imageTable.join(', ')} };
const withImages = (html: string) => html.replace(/\\{\\{(img\\d+)\\}\\}/g, (_, name: string) => images[name]);

export const posts: Post[] = (${JSON.stringify(posts)} as Post[]).map(post => (post.html ? { ...post, html: withImages(post.html) } : post));

/** The articles with bodies in this prototype, in the sample's order. */
export const sampledPosts = ${JSON.stringify(ARTICLE_SAMPLE)}.map(id => posts.find(post => post.id === id)!);
`);
}

